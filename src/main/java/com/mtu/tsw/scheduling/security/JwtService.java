package com.mtu.tsw.scheduling.security;

import java.nio.charset.StandardCharsets;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.Date;
import java.util.Optional;

import javax.crypto.SecretKey;

import org.springframework.stereotype.Component;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Clock;
import io.jsonwebtoken.ExpiredJwtException;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.security.Keys;

@Component
public class JwtService {

    private final SecretKey SECRET_KEY;
    private final long EXPIRATION_TIME_INCREMENT = 1000 * 60 * 60; // 1 hour in ms
    private final Clock clock;

    public JwtService(Clock clock) throws NoSuchAlgorithmException {
        this.clock = clock;
        SECRET_KEY = Keys.hmacShaKeyFor(generateKey().getBytes(StandardCharsets.UTF_8));
    }

    private String generateKey() throws NoSuchAlgorithmException {
        String characterPool = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()-_=+";
        SecureRandom rand = SecureRandom.getInstanceStrong();

        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < 256; i++) {
            builder.append(characterPool.charAt(rand.nextInt(characterPool.length())));
        }

        return builder.toString();
    }

    /**
     * Generate an authentication token for the given username. The generated token will be valid for one hour.
     * @param username Username which will be associated with the generated token
     * @return URL safe authentication token
     */
    public String generateToken(String username) {

        return Jwts.builder()
                .subject(username)
                .issuedAt(clock.now())
                .expiration(new Date(clock.now().getTime() + EXPIRATION_TIME_INCREMENT))
                .signWith(SECRET_KEY)
                .compact();
    }

    /**
     * Extract the username from the given token. Note that this method may return a username for an expired token. It is the callers responsibility to ensure the token is unexpired.
     * @param token Auth token generated by this service
     * @return Username associated with the given token, or an empty optional
     */
    public Optional<String> getUsername(String token) {
        String username = getClaims(token).getSubject();

        if (username == null) {
            return Optional.empty();
        }
        return Optional.of(username);
    }

    /**
     * Determine if the given token is expired or not
     * @param token Token to check
     * @return False if the token is expired, true otherwise.
     * @see {@link #generateToken(String)} for information about token issuing & expiry
     */
    public boolean isTokenUnexpired(String token) {
        Date expire = getClaims(token).getExpiration();

        return expire != null && expire.after(clock.now());
    }

    private Claims getClaims(String token) {
        try {
            return Jwts.parser()
                .clock(clock)
                .verifyWith(SECRET_KEY)
                .build()
                .parseSignedClaims(token)
                .getPayload();
        }catch (ExpiredJwtException e) {
            return e.getClaims(); // empty claims, handled by caller null case
        }
    }

}
